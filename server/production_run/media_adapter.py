class MediaAdapter:
    owner = "media"
    calls_per_target = 80
    seconds_per_target = 7200

    def __init__(
        self,
        sessions: Sessions,
        *,
        authority: RunAutomationAuthority,
        projects: ProjectManager,
        resolver: ConfigResolver,
        planner: WorkflowPlanner | None = None,
        queue: GenerationQueue | None = None,
        tools: dict[WorkflowActionType, MediaTool] | None = None,
        max_attempts: int = 2,
        judge: ImageJudge | None = None,
        restore: Callable[[str, str, str, int], Awaitable[Any]] | None = None,
        continuity: ContinuityJudge | None = None,
        face: FaceIdentityService | None = None,
    ) -> None:
        self._sessions, self._authority, self._projects, self._resolver = sessions, authority, projects, resolver
        self._planner = planner or WorkflowPlanner(projects)
        self._queue = queue or get_generation_queue()
        self._tools = tools or MEDIA_TOOLS
        self._max_attempts = max_attempts
        # Check results by (path, mtime, size): an unchanged file is not decoded again on every poll.
        self._checked: dict[tuple[str, int, int], str | None] = {}
        self._judge_client = judge
        self._continuity = continuity
        self._face = face
        self._restore = restore or restore_resource_version
        # Storyboard selections in flight, off the controller lease, by step command and episode.
        self._jobs: dict[str, asyncio.Task[dict[str, dict[str, Any]]]] = {}
        # Continuity verdicts in flight, off the controller lease, by step command, episode and round.
        self._continuity_jobs: dict[str, asyncio.Task[dict[str, tuple[int | None, Verdict | None]]]] = {}

    async def plan(self, *, run: RunSnapshot) -> StepPlan:
        pins = []
        for target in run.targets:
            episode = episode_number(target)
            status = await self._plan(run.user_id, run.project_name, episode)
            fingerprint = self._script_fingerprint(run.project_name, status)
            pins.append(revision_receipt("script-writer", f"episode:{episode}:script", fingerprint))
        units = len(run.targets)
        return StepPlan(
            unit_key="media",
            input_refs=tuple(pins),
            estimated_cost_minor_units=0,
            estimated_model_calls=self.calls_per_target * units,
            estimated_tasks=self.calls_per_target * units,
            estimated_runtime_seconds=self.seconds_per_target * units,
        )

    async def dispatch(self, intent: DispatchIntent) -> OwnerReceipt:
        digest = digest_value(
            "r2.production-media-stage.v1",
            ensure_json_value({"input_refs": [ref.model_dump(mode="json") for ref in intent.input_refs]}),
        )
        subject = await current_subject(self._sessions, intent, subject_digest=digest)
        async with self._sessions() as session, session.begin():
            await self._authority.require_locked(session, subject=subject)
        return OwnerReceipt(owner=self.owner, receipt_ref=intent.identity.command_id, digest=digest)

    async def inspect(self, *, intent: DispatchIntent, receipt: OwnerReceipt) -> StageOutcome:
        evidence: list[OwnerReceipt] = []
        for pin in intent.input_refs:
            episode = int(pin.receipt_ref.split(":")[1])
            plan = await self._plan(intent.scope.user_id, intent.scope.project_name, episode)
            if self._script_fingerprint(intent.scope.project_name, plan) != receipt_revision(pin):
                raise OwnerBlocked("EXTERNAL_INPUT_CHANGED")
            confirmed: dict[str, int] = {}
            if plan.next_action.type is A.CONFIRM_REQUEST_DURATION:
                # The automatic owner takes the tier the planner proposes for each unit, as a Human confirming it would.
                confirmed = self._proposed_durations(plan)
                if not confirmed:
                    raise OwnerBlocked("WORKFLOW_CONFIRM_REQUEST_DURATION")
                plan = await self._plan(intent.scope.user_id, intent.scope.project_name, episode, confirmed)
            if plan.next_action.type is not A.WAIT_FOR_TASK:
                if await self._redo_reworked_segments(intent, receipt.digest, plan, episode):
                    return outcome(intent, "WAIT", owner_state="REWORK_REGENERATING")
                if await self._redo_failing_units(intent, receipt.digest, plan):
                    return outcome(intent, "WAIT", owner_state="UNIT_REGENERATING")
                if await self._select_storyboards(intent, receipt.digest, plan, episode):
                    return outcome(intent, "WAIT", owner_state="STORYBOARDS_SELECTING")
                if await self._check_continuity(intent, receipt.digest, plan, episode):
                    return outcome(intent, "WAIT", owner_state="STORYBOARDS_CONTINUITY")
            action = plan.next_action
            if action.type is A.EXPORT or (action.type is A.PLAN_EPISODES and self._episode_media_current(plan)):
                artifacts = digest_value("r2.production-media-artifacts.v1", ensure_json_value(plan.status.artifacts))
                evidence.append(revision_receipt(self.owner, f"episode:{episode}:media", artifacts))
                continue
            if action.type is A.WAIT_FOR_TASK:
                return outcome(intent, "WAIT", owner_state="OWNER_TASK_ACTIVE")
            if action.type in _UPSTREAM:
                raise OwnerBlocked("EXTERNAL_INPUT_CHANGED")
            if action.type not in self._tools:
                if plan.blockers:
                    raise OwnerBlocked("WORKFLOW_" + plan.blockers[0].code.upper())
                raise OwnerBlocked("WORKFLOW_" + action.type.value.upper())
            await self._submit(intent, receipt.digest, plan, confirmed)
            return outcome(intent, "WAIT", owner_state="OWNER_TASK_SUBMITTED")
        return outcome(intent, "PASS", receipts=tuple(evidence), owner_state="EXPORT_READY")

    async def usage(self, *, receipt: OwnerReceipt, reservation: BudgetReservation) -> UsageReceipt | None:
        intent = await step_intent(self._sessions, reservation)
        tasks = await attempt_window_tasks(self._sessions, intent)
        return await tasks_usage(self._sessions, tasks, receipt, reservation)

    # --- automatic rework ----------------------------------------------------------------------------

    async def _redo_reworked_segments(
        self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan, episode: int
    ) -> bool:
        """Regenerate, once per generation, the storyboards of the segments the previous final's reviewers named."""
        target = plan.status.target
        run = await self._run(intent)
        if target is None or run is None:
            return False
        segments = self._reworked_segments(run, episode)
        pending = [unit for unit in segments if not await self._attempts(intent, f"rework:storyboards:{unit}")]
        if not pending:
            return False
        args: dict[str, Any] = {"script": target.script_filename, "segment_ids": pending}
        sub_keys = [f"rework:storyboards:{unit}" for unit in pending]
        await self._send(intent, subject_digest, sub_keys, A.GENERATE_STORYBOARDS, args, "MEDIA_RETRY_LIMIT")
        return True

    def _reworked_segments(self, run: RunSnapshot, episode: int) -> list[str]:
        """The segments the previous generation's reviewers named for MEDIA repair when both rejected its final
        under an enforcing quality gate; empty for the first generation, a recording gate or a Human rework."""
        if run.generation < 2 or run.policy.quality_gate != "enforce":
            return []
        folder = (
            self._projects.get_project_path(run.project_name)
            / "production"
            / "automation"
            / run.run_id
            / f"g{run.generation - 1}"
            / f"episode_{episode}"
            / "quality"
        )
        reviews = []
        for role in ("reviewer_a", "reviewer_b"):
            found = sorted(folder.glob(f"*.{role}.json"), key=lambda path: path.stat().st_mtime)
            if not found:
                return []
            try:
                reviews.append(ModelAssessment.model_validate_json(found[-1].read_text(encoding="utf-8")))
            except (OSError, ValueError):
                return []
        if any(review.outcome == "COMPLETED" and review.accepts() for review in reviews):
            return []
        prefix = f"episode:{episode}:segment:"
        return sorted(
            {
                finding.unit_key.removeprefix(prefix)
                for review in reviews
                for finding in review.findings
                if finding.repair_stage is RunStage.MEDIA
                and finding.severity in {"CRITICAL", "MAJOR"}
                and finding.unit_key.startswith(prefix)
            }
        )

    # --- storyboard selection ------------------------------------------------------------------------

    async def _select_storyboards(
        self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan, episode: int
    ) -> bool:
        """Make the policy's extra storyboard versions, then let the ranking judge choose; ``True`` while working."""
        run = await self._run(intent)
        target = plan.status.target
        if run is None or target is None or run.policy.image_candidates < 2 or not self._all_made(plan, "storyboards"):
            return False
        items, id_field = self._script_items(intent.scope.project_name, target.script_filename)
        units = [
            str(item[id_field])
            for item in items
            if item.get(id_field) and (item.get("generated_assets") or {}).get("storyboard_image")
        ]
        for candidate in range(2, run.policy.image_candidates + 1):
            pending = [unit for unit in units if not await self._attempts(intent, f"select:{unit}:v{candidate}")]
            if pending:
                args: dict[str, Any] = {"script": target.script_filename, "segment_ids": pending}
                sub_keys = [f"select:{unit}:v{candidate}" for unit in pending]
                await self._send(intent, subject_digest, sub_keys, A.GENERATE_STORYBOARDS, args, "MEDIA_RETRY_LIMIT")
                return True
        undecided = [unit for unit in units if not await self._attempts(intent, f"select:{unit}:chosen")]
        if not undecided:
            return False
        key = f"{intent.identity.command_id}:select:{episode}"
        job = self._jobs.get(key)
        if job is None:
            lines = {str(item[id_field]): str(item.get("novel_text") or "") for item in items if item.get(id_field)}
            judging = (
                self._judge_by_face(run, target.script_filename, undecided)
                if run.policy.image_judge_identity == FACE_JUDGE_IDENTITY
                else self._judge(run, undecided, lines)
            )
            self._jobs[key] = asyncio.create_task(judging)
            return True
        if not job.done():
            return True
        self._jobs.pop(key, None)
        try:
            decisions = job.result()
        except Exception as error:
            decisions = {unit: {"chosen_version": None, "error": type(error).__name__} for unit in undecided}
        await self._apply_choices(intent, subject_digest, run, episode, decisions)
        return True

    async def _judge(self, run: RunSnapshot, units: list[str], lines: Mapping[str, str]) -> dict[str, dict[str, Any]]:
        """Per segment: the judged candidates (the newest ``image_candidates`` versions that pass their check) and
        the version the judge chose; with fewer than two usable candidates the current version stays."""
        route = next(
            (
                r
                for r in run.policy.routes
                if r.role in {"reviewer_a", "reviewer_b"} and r.model_identity == run.policy.image_judge_identity
            ),
            None,
        )
        root = self._projects.get_project_path(run.project_name)
        versions = VersionManager(root)
        portrait = run.policy.height >= run.policy.width
        decisions: dict[str, dict[str, Any]] = {}
        for unit in units:
            listed = sorted(versions.get_versions("storyboards", unit)["versions"], key=lambda v: v["version"])
            newest = listed[-run.policy.image_candidates :]
            usable = [v for v in newest if storyboard_problem(root / v["file"], portrait=portrait) is None]
            decision: dict[str, Any] = {"candidates": [v["version"] for v in usable], "chosen_version": None}
            if route is not None and self._judge_client is not None and len(usable) >= 2:
                pictures = [await asyncio.to_thread((root / v["file"]).read_bytes) for v in usable]
                choice = await self._judge_client.choose(
                    route, lines.get(unit, ""), pictures, prompt_digest=run.policy.image_judge_prompt_digest
                )
                decision.update(chosen_version=usable[choice.index]["version"], scores=choice.scores)
            decisions[unit] = decision
        return decisions

    async def _judge_by_face(
        self, run: RunSnapshot, script_filename: str, units: list[str]
    ) -> dict[str, dict[str, Any]]:
        """Per segment: the usable candidates and the one whose faces best match the cast's sheets (ADR-0151); a shot
        with no scored face, or with fewer than two usable candidates, keeps its current version."""
        root = self._projects.get_project_path(run.project_name)
        project = await asyncio.to_thread(self._projects.load_project, run.project_name)
        script = await asyncio.to_thread(self._projects.load_script, run.project_name, script_filename)
        versions = VersionManager(root)
        portrait = run.policy.height >= run.policy.width
        decisions: dict[str, dict[str, Any]] = {}
        for unit in units:
            listed = sorted(versions.get_versions("storyboards", unit)["versions"], key=lambda v: v["version"])
            newest = listed[-run.policy.image_candidates :]
            usable = [v for v in newest if storyboard_problem(root / v["file"], portrait=portrait) is None]
            decision: dict[str, Any] = {"candidates": [v["version"] for v in usable], "chosen_version": None}
            shot = await asyncio.to_thread(continuity_pass.shot_for, project, root, script, unit)
            sheets = [data for label, data in (shot.references if shot else ()) if label.startswith("character:")]
            if self._face is not None and sheets and len(usable) >= 2:
                pictures = [await asyncio.to_thread((root / v["file"]).read_bytes) for v in usable]
                index, scores = await self._face.choose(sheets, pictures)
                decision["scores"] = scores
                if index is not None:
                    decision["chosen_version"] = usable[index]["version"]
            decisions[unit] = decision
        return decisions

    async def _apply_choices(
        self,
        intent: DispatchIntent,
        subject_digest: str,
        run: RunSnapshot,
        episode: int,
        decisions: Mapping[str, dict[str, Any]],
    ) -> None:
        """Per segment, under the run's locked authority: record the choice write-ahead and add it to
        ``image_selection.json`` beside the episode's render; then restore a chosen version that is not current."""
        root = self._projects.get_project_path(run.project_name)
        versions = VersionManager(root)
        evidence = root / "production" / "automation" / run.run_id / f"g{run.generation}" / f"episode_{episode}"
        evidence /= "image_selection.json"
        subject = await current_subject(self._sessions, intent, subject_digest=subject_digest)
        for unit, decision in sorted(decisions.items()):
            chosen = decision.get("chosen_version")
            restore = (
                isinstance(chosen, int) and chosen != versions.get_versions("storyboards", unit)["current_version"]
            )
            async with self._sessions() as session, session.begin():
                await self._authority.require_locked(session, subject=subject)
                await ProductionRunRepository(session).record_owner_attempt(
                    intent=intent, sub_key=f"select:{unit}:chosen"
                )
                await asyncio.to_thread(
                    self._record_choice, evidence, run, unit, {**decision, "restore_requested": restore}
                )
            if restore and isinstance(chosen, int):
                await self._restore(run.project_name, "storyboards", unit, chosen)

    @staticmethod
    def _record_choice(evidence: Path, run: RunSnapshot, unit: str, decision: dict[str, Any]) -> None:
        evidence.parent.mkdir(parents=True, exist_ok=True)
        recorded = json.loads(evidence.read_text(encoding="utf-8")) if evidence.is_file() else {}
        recorded.update(
            {
                "schema": "r2.production-image-selection.v1",
                "judge_identity": run.policy.image_judge_identity,
                "judge_prompt_digest": run.policy.image_judge_prompt_digest,
                "candidates": run.policy.image_candidates,
                "segments": {**recorded.get("segments", {}), unit: decision},
            }
        )
        evidence.write_text(json.dumps(recorded, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")

    # --- continuity ----------------------------------------------------------------------------------

    async def _check_continuity(
        self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan, episode: int
    ) -> bool:
        """Judge, regenerate drifts once with their fix, judge again; ``True`` while working."""
        run = await self._run(intent)
        target = plan.status.target
        if (
            run is None
            or target is None
            or run.policy.continuity_judge_identity is None
            or self._continuity is None
            or not self._all_made(plan, "storyboards")
        ):
            return False
        items, id_field = self._script_items(intent.scope.project_name, target.script_filename)
        units = [
            str(item[id_field])
            for item in items
            if item.get(id_field) and (item.get("generated_assets") or {}).get("storyboard_image")
        ]
        first = [unit for unit in units if not await self._attempts(intent, f"continuity:{unit}:judged")]
        if first:
            return await self._continuity_round(intent, subject_digest, run, episode, "judged", first, target)
        segments = continuity_pass.read_evidence(self._continuity_evidence(run, episode)).get("segments") or {}
        fixes = {
            unit: fix
            for unit in units
            if isinstance(verdict := (segments.get(unit) or {}).get("first", {}).get("verdict"), dict)
            and verdict.get("status") == "drift"
            and isinstance(fix := verdict.get("prompt_fix"), str)
            and fix.strip()
            and not await self._attempts(intent, f"continuity:{unit}:redo")
        }
        if fixes:
            args: dict[str, Any] = {
                "script": target.script_filename,
                "segment_ids": sorted(fixes),
                "prompt_addenda": {unit: fix.strip()[:600] for unit, fix in fixes.items()},
            }
            sub_keys = [f"continuity:{unit}:redo" for unit in sorted(fixes)]
            await self._send(intent, subject_digest, sub_keys, A.GENERATE_STORYBOARDS, args, "MEDIA_RETRY_LIMIT")
            return True
        second = [
            unit
            for unit in units
            if await self._attempts(intent, f"continuity:{unit}:redo")
            and not await self._attempts(intent, f"continuity:{unit}:rejudged")
        ]
        if second:
            return await self._continuity_round(intent, subject_digest, run, episode, "rejudged", second, target)
        return False

    async def _continuity_round(
        self,
        intent: DispatchIntent,
        subject_digest: str,
        run: RunSnapshot,
        episode: int,
        round_name: str,
        units: list[str],
        target: Any,
    ) -> bool:
        key = f"{intent.identity.command_id}:continuity:{episode}:{round_name}"
        job = self._continuity_jobs.get(key)
        if job is None:
            self._continuity_jobs[key] = asyncio.create_task(self._judge_continuity(run, target.script_filename, units))
            return True
        if not job.done():
            return True
        self._continuity_jobs.pop(key, None)
        try:
            verdicts = job.result()
        except Exception:
            verdicts = dict.fromkeys(units, (None, None))
        await self._apply_continuity(intent, subject_digest, run, episode, round_name, verdicts)
        return True

    async def _judge_continuity(
        self, run: RunSnapshot, script_filename: str, units: list[str]
    ) -> dict[str, tuple[int | None, Verdict | None]]:
        """Per segment: the current storyboard version and the pinned judge's verdict on it (``None``: no verdict)."""
        route = next(
            (
                r
                for r in run.policy.routes
                if r.role in {"reviewer_a", "reviewer_b"} and r.model_identity == run.policy.continuity_judge_identity
            ),
            None,
        )
        root = self._projects.get_project_path(run.project_name)
        project = await asyncio.to_thread(self._projects.load_project, run.project_name)
        script = await asyncio.to_thread(self._projects.load_script, run.project_name, script_filename)
        versions = VersionManager(root)
        verdicts: dict[str, tuple[int | None, Verdict | None]] = {}
        for unit in units:
            current = versions.get_versions("storyboards", unit)["current_version"]
            listed = {v["version"]: v for v in versions.get_versions("storyboards", unit)["versions"]}
            entry = listed.get(current)
            shot = await asyncio.to_thread(continuity_pass.shot_for, project, root, script, unit)
            verdict = None
            if route is not None and self._continuity is not None and shot is not None and entry is not None:
                frame = await asyncio.to_thread((root / entry["file"]).read_bytes)
                verdict = await self._continuity.judge(
                    route, shot, frame, max_pictures=run.policy.continuity_judge_max_pictures
                )
            verdicts[unit] = (current if isinstance(current, int) else None, verdict)
        return verdicts

    def _continuity_evidence(self, run: RunSnapshot, episode: int) -> Path:
        root = self._projects.get_project_path(run.project_name)
        folder = root / "production" / "automation" / run.run_id / f"g{run.generation}" / f"episode_{episode}"
        return folder / "continuity.json"

    async def _apply_continuity(
        self,
        intent: DispatchIntent,
        subject_digest: str,
        run: RunSnapshot,
        episode: int,
        round_name: str,
        verdicts: Mapping[str, tuple[int | None, Verdict | None]],
    ) -> None:
        """Under the run's locked authority, per segment: record the round write-ahead and its verdict in
        ``continuity.json``; after the second round, restore the first version when it scored higher."""
        evidence = self._continuity_evidence(run, episode)
        identity = run.policy.continuity_judge_identity or ""
        digest = run.policy.continuity_judge_prompt_digest or ""
        subject = await current_subject(self._sessions, intent, subject_digest=subject_digest)
        for unit, (version, verdict) in sorted(verdicts.items()):
            fields: dict[str, Any] = {
                ("first" if round_name == "judged" else "second"): continuity_pass.judged(version, verdict)
            }
            restore: int | None = None
            if round_name == "rejudged":
                earlier = (continuity_pass.read_evidence(evidence).get("segments") or {}).get(unit) or {}
                before = earlier.get("first") or {}
                old_score = (before.get("verdict") or {}).get("score")
                old_version = before.get("version")
                if (
                    isinstance(old_score, int)
                    and isinstance(old_version, int)
                    and old_version != version
                    and verdict is not None
                    and verdict.score < old_score
                ):
                    restore = old_version
                fields["kept_version"] = restore if restore is not None else version
            async with self._sessions() as session, session.begin():
                await self._authority.require_locked(session, subject=subject)
                await ProductionRunRepository(session).record_owner_attempt(
                    intent=intent, sub_key=f"continuity:{unit}:{round_name}"
                )
                await asyncio.to_thread(
                    continuity_pass.record, evidence, identity=identity, prompt_digest=digest, unit=unit, fields=fields
                )
            if restore is not None:
                await self._restore(run.project_name, "storyboards", unit, restore)

    # --- unit checks ---------------------------------------------------------------------------------

    async def _redo_failing_units(self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan) -> bool:
        """Regenerate the episode's units that fail their check, then the clips of units made again; ``True`` when a
        regeneration was submitted. Kinds whose units are not all made yet are not checked."""
        target = plan.status.target
        if target is None:
            return False
        project = intent.scope.project_name
        items, id_field = self._script_items(project, target.script_filename)
        if not items:
            return False
        portrait = await self._portrait(intent)
        root = self._projects.get_project_path(project)
        redone: set[str] = set()
        for field, collection, reason, action in _UNIT_KINDS:
            if not self._all_made(plan, collection):
                continue
            failing = []
            for item in items:
                unit = str(item.get(id_field) or "")
                path = (item.get("generated_assets") or {}).get(field)
                if not unit or not isinstance(path, str) or not path:
                    continue
                sub_key = f"unit:{collection}:{unit}"
                if await self._attempts(intent, sub_key) or (
                    collection == "storyboards"
                    and (
                        await self._attempts(intent, f"rework:storyboards:{unit}")
                        or await self._attempts(intent, f"select:{unit}:chosen")
                    )
                ):
                    redone.add(unit)
                if self._unit_problem(root / path, field, portrait) is not None:
                    failing.append(unit)
            if not failing and collection == "storyboards":
                # A storyboard the selection judge already chose keeps the judge's pick (ADR-0151 over ADR-0145).
                failing = [
                    unit
                    for unit in self._look_outliers(root, items, id_field)
                    if not await self._attempts(intent, f"unit:{collection}:{unit}")
                    and not await self._attempts(intent, f"select:{unit}:chosen")
                ]
            if failing:
                ids = sorted(failing)
                args: dict[str, Any] = {"script": target.script_filename, "segment_ids": ids}
                await self._send(
                    intent, subject_digest, [f"unit:{collection}:{unit}" for unit in ids], action, args, reason
                )
                return True
        stale = [unit for unit in sorted(redone) if self._clip_older_than_inputs(root, items, id_field, unit)]
        if stale:
            args = {
                "script": target.script_filename,
                "target": {"scope": "selected", "ids": stale},
                "narration_delivery": USE_TTS,
                "force": True,
            }
            await self._send(
                intent,
                subject_digest,
                [f"unit:videos:{unit}" for unit in stale],
                A.GENERATE_VIDEOS,
                args,
                "MEDIA_RETRY_LIMIT",
            )
            return True
        return False

    @staticmethod
    def _look_outliers(root: Path, items: list[dict[str, Any]], id_field: str) -> list[str]:
        """Storyboards lit or coloured unlike the rest of their scene; only shots carrying a scene look are grouped."""
        starts = scene_starts([item for item in items if item.get(id_field)], id_field=id_field)
        scenes: dict[str, list[tuple[str, tuple[float, float]]]] = {}
        for item in items:
            unit = str(item.get(id_field) or "")
            path = (item.get("generated_assets") or {}).get("storyboard_image")
            if not unit or kept_look(item) is None or not isinstance(path, str):
                continue
            stats = look_stats(root / path)
            if stats is not None:
                scenes.setdefault(starts[unit], []).append((unit, stats))
        return look_outliers(scenes)

    def _unit_problem(self, path: Path, field: str, portrait: bool) -> str | None:
        stat = path.stat() if path.is_file() else None
        key = (str(path), stat.st_mtime_ns if stat else 0, stat.st_size if stat else -1)
        if key not in self._checked:
            self._checked[key] = (
                storyboard_problem(path, portrait=portrait) if field == "storyboard_image" else narration_problem(path)
            )
        return self._checked[key]

    @staticmethod
    def _all_made(plan: WorkflowPlan, collection: str) -> bool:
        found = plan.status.artifacts.get(collection)
        return isinstance(found, dict) and bool(found.get("current_ids")) and not found.get("missing_ids")

    @staticmethod
    def _clip_older_than_inputs(root: Path, items: list[dict[str, Any]], id_field: str, unit: str) -> bool:
        item = next((i for i in items if str(i.get(id_field)) == unit), None)
        assets = (item or {}).get("generated_assets") or {}
        clip = assets.get("video_clip")
        if not isinstance(clip, str) or not (root / clip).is_file():
            return False
        inputs = [
            root / p for p in (assets.get("storyboard_image"), assets.get("narration_audio")) if isinstance(p, str)
        ]
        newest = max((p.stat().st_mtime_ns for p in inputs if p.is_file()), default=0)
        return (root / clip).stat().st_mtime_ns < newest

    def _script_items(self, project: str, script_filename: str) -> tuple[list[dict[str, Any]], str]:
        try:
            items, id_field, *_ = get_storyboard_items(self._projects.load_script(project, script_filename))
        except (FileNotFoundError, ValueError, KeyError):
            return [], ""
        return [i for i in items if isinstance(i, dict)], id_field

    async def _run(self, intent: DispatchIntent) -> RunSnapshot | None:
        async with self._sessions() as session:
            return await ProductionRunRepository(session).get(**intent.scope.model_dump())

    async def _portrait(self, intent: DispatchIntent) -> bool:
        run = await self._run(intent)
        return run is None or run.policy.height >= run.policy.width

    async def _attempts(self, intent: DispatchIntent, sub_key: str) -> int:
        async with self._sessions() as session:
            return await ProductionRunRepository(session).owner_attempts(intent=intent, sub_key=sub_key)

    async def _send(
        self,
        intent: DispatchIntent,
        subject_digest: str,
        sub_keys: list[str],
        action: WorkflowActionType,
        args: dict[str, Any],
        limit_reason: str,
    ) -> None:
        """Send one tool call for several units, each unit's attempt recorded write-ahead under its own sub key."""
        for sub_key in sub_keys:
            if await self._attempts(intent, sub_key) >= MEDIA_UNIT_RETRY_LIMIT:
                raise OwnerBlocked(limit_reason)
        subject = await current_subject(self._sessions, intent, subject_digest=subject_digest)
        async with self._sessions() as session, session.begin():
            await self._authority.require_locked(session, subject=subject)
            repository = ProductionRunRepository(session)
            for sub_key in sub_keys:
                await repository.record_owner_attempt(intent=intent, sub_key=sub_key)
        submitted = await self._tools[action](self._context(intent), args)
        if submitted.problem is not None:
            raise OwnerBlocked("MEDIA_" + submitted.problem.code.upper())

    def _context(self, intent: DispatchIntent) -> ToolContext:
        return ToolContext(
            intent.scope.project_name,
            Path(self._projects.projects_root),
            self._projects,
            config_resolver=self._resolver,
            caller=CallerContext(user_id=intent.scope.user_id, source="mcp"),
            queue=self._queue,
        )

