"""``MEDIA``: asset sheets, storyboards, narration audio and video units for every target episode.

The workflow planner owns what each episode still needs (with the run's narration delivery, ``use_tts``); the step
submits that action through the same media tools the agent uses and waits while the planner reports active tasks.
An episode is done when its plan asks for ``export``. Each owner action is recorded write-ahead before it is sent
and is tried at most ``max_attempts`` times; a plan that still asks for it after that blocks the run. Actions that
need a script edit, a paid-duration confirmation or provider configuration are never taken automatically.

Once an episode's storyboards (or narration lines) all exist, each one passes the deterministic unit checks of
:mod:`server.production_run.unit_checks`; a failing unit is regenerated by explicit id at most
``MEDIA_UNIT_RETRY_LIMIT`` times, and its clip is made again once the unit passes (ADR-0112).

After an automatic QUALITY rework (``quality_gate`` ``enforce``, both reviewers rejected the previous generation's
final), the storyboard and then the clip of every segment a MEDIA-repairable finding names are made again once at
the new generation before ordinary planning; a Human rework regenerates nothing on its own.

When the run's policy asks for several storyboard candidates, MEDIA makes the extra versions of every storyboard one
round at a time, has the pinned ranking judge (the reviewer route with the pinned identity) choose per segment off the lease, restores
each winner as the current version and records the choices in ``image_selection.json`` beside the episode's render.

When the run's policy pins a continuity judge (ADR-0134), MEDIA then judges every storyboard against its reference
sheets and previous frame off the lease, regenerates once each storyboard judged a drift with the verdict's
``prompt_fix`` as the task's prompt addendum, judges the new version and keeps the better-scoring one; the verdicts go
to ``continuity.json`` beside the episode's render. A judge that gives no verdict keeps the frame; nothing blocks.

Every target's final script is pinned when the stage is planned; a different current script is an external change.
"""

