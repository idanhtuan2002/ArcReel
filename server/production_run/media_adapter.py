type MediaTool = Callable[[ToolContext, dict[str, Any]], Awaitable[ToolOutcome[Any]]]

A = WorkflowActionType
MEDIA_TOOLS: dict[WorkflowActionType, MediaTool] = {
    A.GENERATE_ASSET_SHEETS: handle_generate_assets,
    A.GENERATE_STORYBOARDS: handle_generate_storyboards,
    A.GENERATE_TTS: handle_generate_narration_audio,
    A.REGENERATE_TTS: handle_generate_narration_audio,
    A.GENERATE_VIDEOS: handle_generate_videos,
}
MEDIA_UNIT_RETRY_LIMIT = 2
#: (unit asset field, plan artifact collection, reason once a unit exhausts its retries, regenerating action)
_UNIT_KINDS = (
    ("storyboard_image", "storyboards", "MEDIA_IMAGE_CHECK_FAILED", A.GENERATE_STORYBOARDS),
    ("narration_audio", "audio", "MEDIA_TTS_CHECK_FAILED", A.REGENERATE_TTS),
)
_UPSTREAM = frozenset(
    {
        A.COLLECT_PROJECT_INPUT,
        A.ANALYZE_ASSETS,
        A.PLAN_EPISODES,
        A.RESET_EPISODE_PLANNING,
        A.PREPARE_SCRIPT_PLAN,
        A.CONFIRM_SCRIPT_PLAN,
        A.GENERATE_SCRIPT,
    }
)


class MediaAdapter:
    owner = "media"
    calls_per_target = 80
    seconds_per_target = 7200

    def __init__(
        self,
        sessions: Sessions,
        *,
        authority: RunAutomationAuthority,
        projects: ProjectManager,
        resolver: ConfigResolver,
        planner: WorkflowPlanner | None = None,
        queue: GenerationQueue | None = None,
        tools: dict[WorkflowActionType, MediaTool] | None = None,
        max_attempts: int = 2,
    ) -> None:
        self._sessions, self._authority, self._projects, self._resolver = sessions, authority, projects, resolver
        self._planner = planner or WorkflowPlanner(projects)
        self._queue = queue or get_generation_queue()
        self._tools = tools or MEDIA_TOOLS
        self._max_attempts = max_attempts
        # Check results by (path, mtime, size): an unchanged file is not decoded again on every poll.
        self._checked: dict[tuple[str, int, int], str | None] = {}

    async def plan(self, *, run: RunSnapshot) -> StepPlan:
        pins = []
        for target in run.targets:
            episode = episode_number(target)
            status = await self._plan(run.user_id, run.project_name, episode)
            fingerprint = self._script_fingerprint(run.project_name, status)
            pins.append(revision_receipt("script-writer", f"episode:{episode}:script", fingerprint))
        units = len(run.targets)
        return StepPlan(
            unit_key="media",
            input_refs=tuple(pins),
            estimated_cost_minor_units=0,
            estimated_model_calls=self.calls_per_target * units,
            estimated_tasks=self.calls_per_target * units,
            estimated_runtime_seconds=self.seconds_per_target * units,
        )

    async def dispatch(self, intent: DispatchIntent) -> OwnerReceipt:
        digest = digest_value(
            "r2.production-media-stage.v1",
            ensure_json_value({"input_refs": [ref.model_dump(mode="json") for ref in intent.input_refs]}),
        )
        subject = await current_subject(self._sessions, intent, subject_digest=digest)
        async with self._sessions() as session, session.begin():
            await self._authority.require_locked(session, subject=subject)
        return OwnerReceipt(owner=self.owner, receipt_ref=intent.identity.command_id, digest=digest)

    async def inspect(self, *, intent: DispatchIntent, receipt: OwnerReceipt) -> StageOutcome:
        evidence: list[OwnerReceipt] = []
        for pin in intent.input_refs:
            episode = int(pin.receipt_ref.split(":")[1])
            plan = await self._plan(intent.scope.user_id, intent.scope.project_name, episode)
            if self._script_fingerprint(intent.scope.project_name, plan) != receipt_revision(pin):
                raise OwnerBlocked("EXTERNAL_INPUT_CHANGED")
            confirmed: dict[str, int] = {}
            if plan.next_action.type is A.CONFIRM_REQUEST_DURATION:
                # The automatic owner takes the tier the planner proposes for each unit, as a Human confirming it would.
                confirmed = self._proposed_durations(plan)
                if not confirmed:
                    raise OwnerBlocked("WORKFLOW_CONFIRM_REQUEST_DURATION")
                plan = await self._plan(intent.scope.user_id, intent.scope.project_name, episode, confirmed)
            if plan.next_action.type is not A.WAIT_FOR_TASK and await self._redo_failing_units(
                intent, receipt.digest, plan
            ):
                return outcome(intent, "WAIT", owner_state="UNIT_REGENERATING")
            action = plan.next_action
            if action.type is A.EXPORT or (action.type is A.PLAN_EPISODES and self._episode_media_current(plan)):
                artifacts = digest_value("r2.production-media-artifacts.v1", ensure_json_value(plan.status.artifacts))
                evidence.append(revision_receipt(self.owner, f"episode:{episode}:media", artifacts))
                continue
            if action.type is A.WAIT_FOR_TASK:
                return outcome(intent, "WAIT", owner_state="OWNER_TASK_ACTIVE")
            if action.type in _UPSTREAM:
                raise OwnerBlocked("EXTERNAL_INPUT_CHANGED")
            if action.type not in self._tools:
                if plan.blockers:
                    raise OwnerBlocked("WORKFLOW_" + plan.blockers[0].code.upper())
                raise OwnerBlocked("WORKFLOW_" + action.type.value.upper())
            await self._submit(intent, receipt.digest, plan, confirmed)
            return outcome(intent, "WAIT", owner_state="OWNER_TASK_SUBMITTED")
        return outcome(intent, "PASS", receipts=tuple(evidence), owner_state="EXPORT_READY")

    async def usage(self, *, receipt: OwnerReceipt, reservation: BudgetReservation) -> UsageReceipt | None:
        intent = await step_intent(self._sessions, reservation)
        tasks = await attempt_window_tasks(self._sessions, intent)
        return await tasks_usage(self._sessions, tasks, receipt, reservation)

    # --- unit checks ---------------------------------------------------------------------------------

    async def _redo_failing_units(self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan) -> bool:
        """Regenerate the episode's units that fail their check, then the clips of units made again; ``True`` when a
        regeneration was submitted. Kinds whose units are not all made yet are not checked."""
        target = plan.status.target
        if target is None:
            return False
        project = intent.scope.project_name
        items, id_field = self._script_items(project, target.script_filename)
        if not items:
            return False
        portrait = await self._portrait(intent)
        root = self._projects.get_project_path(project)
        redone: set[str] = set()
        for field, collection, reason, action in _UNIT_KINDS:
            if not self._all_made(plan, collection):
                continue
            failing = []
            for item in items:
                unit = str(item.get(id_field) or "")
                path = (item.get("generated_assets") or {}).get(field)
                if not unit or not isinstance(path, str) or not path:
                    continue
                sub_key = f"unit:{collection}:{unit}"
                if await self._attempts(intent, sub_key):
                    redone.add(unit)
                if self._unit_problem(root / path, field, portrait) is not None:
                    failing.append(unit)
            if failing:
                ids = sorted(failing)
                args: dict[str, Any] = {"script": target.script_filename, "segment_ids": ids}
                await self._send(
                    intent, subject_digest, [f"unit:{collection}:{unit}" for unit in ids], action, args, reason
                )
                return True
        stale = [unit for unit in sorted(redone) if self._clip_older_than_inputs(root, items, id_field, unit)]
        if stale:
            args = {
                "script": target.script_filename,
                "target": {"scope": "selected", "ids": stale},
                "narration_delivery": USE_TTS,
                "force": True,
            }
            await self._send(
                intent,
                subject_digest,
                [f"unit:videos:{unit}" for unit in stale],
                A.GENERATE_VIDEOS,
                args,
                "MEDIA_RETRY_LIMIT",
            )
            return True
        return False

    def _unit_problem(self, path: Path, field: str, portrait: bool) -> str | None:
        stat = path.stat() if path.is_file() else None
        key = (str(path), stat.st_mtime_ns if stat else 0, stat.st_size if stat else -1)
        if key not in self._checked:
            self._checked[key] = (
                storyboard_problem(path, portrait=portrait) if field == "storyboard_image" else narration_problem(path)
            )
        return self._checked[key]

    @staticmethod
    def _all_made(plan: WorkflowPlan, collection: str) -> bool:
        found = plan.status.artifacts.get(collection)
        return isinstance(found, dict) and bool(found.get("current_ids")) and not found.get("missing_ids")

    @staticmethod
    def _clip_older_than_inputs(root: Path, items: list[dict[str, Any]], id_field: str, unit: str) -> bool:
        item = next((i for i in items if str(i.get(id_field)) == unit), None)
        assets = (item or {}).get("generated_assets") or {}
        clip = assets.get("video_clip")
        if not isinstance(clip, str) or not (root / clip).is_file():
            return False
        inputs = [
            root / p for p in (assets.get("storyboard_image"), assets.get("narration_audio")) if isinstance(p, str)
        ]
        newest = max((p.stat().st_mtime_ns for p in inputs if p.is_file()), default=0)
        return (root / clip).stat().st_mtime_ns < newest

    def _script_items(self, project: str, script_filename: str) -> tuple[list[dict[str, Any]], str]:
        try:
            items, id_field, *_ = get_storyboard_items(self._projects.load_script(project, script_filename))
        except (FileNotFoundError, ValueError, KeyError):
            return [], ""
        return [i for i in items if isinstance(i, dict)], id_field

    async def _portrait(self, intent: DispatchIntent) -> bool:
        async with self._sessions() as session:
            run = await ProductionRunRepository(session).get(**intent.scope.model_dump())
        return run is None or run.policy.height >= run.policy.width

    async def _attempts(self, intent: DispatchIntent, sub_key: str) -> int:
        async with self._sessions() as session:
            return await ProductionRunRepository(session).owner_attempts(intent=intent, sub_key=sub_key)

    async def _send(
        self,
        intent: DispatchIntent,
        subject_digest: str,
        sub_keys: list[str],
        action: WorkflowActionType,
        args: dict[str, Any],
        limit_reason: str,
    ) -> None:
        """Send one tool call for several units, each unit's attempt recorded write-ahead under its own sub key."""
        for sub_key in sub_keys:
            if await self._attempts(intent, sub_key) >= MEDIA_UNIT_RETRY_LIMIT:
                raise OwnerBlocked(limit_reason)
        subject = await current_subject(self._sessions, intent, subject_digest=subject_digest)
        async with self._sessions() as session, session.begin():
            await self._authority.require_locked(session, subject=subject)
            repository = ProductionRunRepository(session)
            for sub_key in sub_keys:
                await repository.record_owner_attempt(intent=intent, sub_key=sub_key)
        submitted = await self._tools[action](self._context(intent), args)
        if submitted.problem is not None:
            raise OwnerBlocked("MEDIA_" + submitted.problem.code.upper())

    def _context(self, intent: DispatchIntent) -> ToolContext:
        return ToolContext(
            intent.scope.project_name,
            Path(self._projects.projects_root),
            self._projects,
            config_resolver=self._resolver,
            caller=CallerContext(user_id=intent.scope.user_id, source="mcp"),
            queue=self._queue,
        )

    # --- helpers -------------------------------------------------------------------------------------

    async def _plan(
        self, user_id: str, project_name: str, episode: int, confirmed: Mapping[str, int] | None = None
    ) -> WorkflowPlan:
        return await self._planner.get_plan(
            project_name,
            WorkflowPlanRequest(
                episode=episode, narration_delivery=USE_TTS, confirmed_request_durations=dict(confirmed or {})
            ),
            user_id=user_id,
            queue=self._queue,
            config_resolver=self._resolver,
        )

    def _script_fingerprint(self, project_name: str, plan: WorkflowPlan) -> str:
        target = plan.status.target
        fingerprint = (
            script_revision(self._projects.get_project_path(project_name) / target.script)
            if target is not None
            else None
        )
        if fingerprint is None:
            raise OwnerBlocked("UPSTREAM_RECEIPT_MISSING")
        return fingerprint

    async def _submit(
        self, intent: DispatchIntent, subject_digest: str, plan: WorkflowPlan, confirmed: Mapping[str, int]
    ) -> None:
        action = plan.next_action
        target = plan.status.target
        assert target is not None
        for sub_key, args in self._requests(plan, target.script_filename, confirmed):
            async with self._sessions() as session:
                attempts = await ProductionRunRepository(session).owner_attempts(intent=intent, sub_key=sub_key)
            if attempts >= self._max_attempts:
                raise OwnerBlocked("MEDIA_RETRY_LIMIT")
            subject = await current_subject(self._sessions, intent, subject_digest=subject_digest)
            async with self._sessions() as session, session.begin():
                await self._authority.require_locked(session, subject=subject)
                await ProductionRunRepository(session).record_owner_attempt(intent=intent, sub_key=sub_key)
            submitted = await self._tools[action.type](self._context(intent), args)
            if submitted.problem is not None:
                raise OwnerBlocked("MEDIA_" + submitted.problem.code.upper())

    @staticmethod
    def _episode_media_current(plan: WorkflowPlan) -> bool:
        """The target episode's script and every unit's storyboard, video and audio are current.

        The plan names a project-wide next step (planning more episodes from the remaining source) once the
        target episode is complete; that step is outside this run's targets."""
        artifacts = plan.status.artifacts
        script = artifacts.get("script")
        if not isinstance(script, dict) or script.get("state") != "current":
            return False
        for kind in ("storyboards", "videos", "audio"):
            collection = artifacts.get(kind)
            if not isinstance(collection, dict) or not collection.get("current_ids"):
                return False
            if collection.get("missing_ids") or collection.get("stale_ids"):
                return False
        return True

    @staticmethod
    def _proposed_durations(plan: WorkflowPlan) -> dict[str, int]:
        """Each unit's proposed request duration where the plan asks to confirm a different tier."""
        admission = plan.next_action.args.get("admission")
        units = admission.get("units") if isinstance(admission, dict) else None
        proposed: dict[str, int] = {}
        for unit in units if isinstance(units, list) else []:
            if not isinstance(unit, dict):
                continue
            seconds = unit.get("request_duration_seconds")
            problems = unit.get("problems") or []
            if (
                isinstance(seconds, int)
                and seconds > 0
                and any(p.get("action") == A.CONFIRM_REQUEST_DURATION.value for p in problems if isinstance(p, dict))
            ):
                proposed[str(unit["unit_id"])] = seconds
        return proposed

    @staticmethod
    def _requests(
        plan: WorkflowPlan, script: str, confirmed: Mapping[str, int] | None = None
    ) -> list[tuple[str, dict[str, Any]]]:
        """The tool calls for the plan's next action, each with the sub key its attempts are counted under."""
        action = plan.next_action
        ids = sorted(action.requested_ids)
        key = (
            action.type.value
            + ":"
            + digest_value("r2.production-media-request.v1", ensure_json_value({"script": script, "ids": ids}))
        )
        if action.type is A.GENERATE_ASSET_SHEETS:
            by_type = MediaAdapter._missing_sheets_by_type(plan, ids)
            return [(f"{key}:{kind}", {"type": kind, "names": names}) for kind, names in sorted(by_type.items())]
        if action.type is A.GENERATE_STORYBOARDS:
            return [(key, {"script": script, **({"segment_ids": ids} if ids else {})})]
        if action.type in {A.GENERATE_TTS, A.REGENERATE_TTS}:
            segments = MediaAdapter._tts_segments(plan) or ids
            if action.type is A.REGENERATE_TTS and not segments:
                raise OwnerBlocked("MEDIA_TTS_SEGMENTS_UNKNOWN")
            return [(key, {"script": script, **({"segment_ids": segments} if segments else {})})]
        episode = plan.status.target.episode if plan.status.target is not None else 0
        scope: dict[str, Any] = {"scope": "selected", "ids": ids} if ids else {"scope": "episode", "episode": episode}
        return [
            (
                key,
                {
                    "script": script,
                    "target": scope,
                    "narration_delivery": USE_TTS,
                    **({"force": True} if ids else {}),
                    **({"confirmed_request_durations": dict(confirmed)} if confirmed else {}),
                },
            )
        ]

    @staticmethod
    def _missing_sheets_by_type(plan: WorkflowPlan, ids: list[str]) -> dict[str, list[str]]:
        """Requested asset names grouped by asset type, from the plan's per-type missing sheet ids.

        The action names assets without their type; a name missing under several types is requested under each.
        A name no type lists blocks the step.
        """
        sheets = plan.status.artifacts.get("asset_sheets")
        by_type: dict[str, list[str]] = {}
        for kind, collection in sorted(sheets.items()) if isinstance(sheets, dict) else ():
            missing = collection.get("missing_ids", []) if isinstance(collection, dict) else []
            names = [name for name in ids if name in missing]
            if names:
                by_type[kind] = names
        if {name for names in by_type.values() for name in names} != set(ids):
            raise OwnerBlocked("MEDIA_ASSET_TYPE_UNKNOWN")
        return by_type

    @staticmethod
    def _tts_segments(plan: WorkflowPlan) -> list[str]:
        admission = plan.next_action.args.get("admission")
        units = admission.get("units") if isinstance(admission, dict) else None
        wanted = {A.GENERATE_TTS.value, A.REGENERATE_TTS.value}
        segments = {
            str(unit.get("unit_id"))
            for unit in units or []
            if isinstance(unit, dict)
            and any(isinstance(p, dict) and p.get("action") in wanted for p in unit.get("problems") or [])
        }
        return sorted(segments)


