"""Project preparation, Vietnamese voice casting and face prompts for a DramaClaw film run (ASSEMBLY_PLAN M2).

- Preparation follows the Hermes init playbook Steps 1-3 (`ingest/upload`, `ingest/start`, `PATCH /projects/{p}`); the
  project itself is created here because the connector has no front end.
- Casting (D9, D18): each character and the narrator get a VieNeu preset (`assembly.voices.casting`); a short sample
  in that preset is generated by the VieNeu shim, registered by SHA-256 (`assembly.voices.registry`) and uploaded to
  DramaClaw's own voice slots, so DramaClaw's IndexTTS2 path sends it back to `assembly.voice_adapter`.
- Face prompts: the init playbook's Step 5 rule, done by a text model through DramaClaw's NewAPI (the Hermes agent
  does it with its own model).
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import time
import unicodedata
from pathlib import Path
from typing import Any

import httpx

from assembly.connector.dramaclaw_tools import DEFAULT_API_URL, DramaClawTools
from assembly.connector.film import FilmRun, RunStopped, chapter_text, wait_task
from assembly.voices import registry
from assembly.voices.casting import CastMember, cast
from assembly.voices.catalog import load_voices

VIENEU_URL = os.environ.get("VIENEU_SHIM_URL", "http://127.0.0.1:23340")
NEWAPI_URL = os.environ.get("ASSEMBLY_NEWAPI_URL", "http://127.0.0.1:3000")
SAMPLE_LINE = "Xin chào, tôi là {name}. Hôm nay trời trong, tôi kể bạn nghe một câu chuyện nhỏ của gia đình mình."
NARRATOR_LINE = "Câu chuyện bắt đầu vào một buổi chiều cuối thu, khi chiếc đồng hồ cũ trên tường bỗng ngừng chạy."
FACE_PROMPT_RULE = (
    "根据角色名、性别、年龄段、description 生成一句具体面部特征描述。"
    "face_prompt 只写脸部特征：发型、脸型、五官、肤色、年龄感、气质；不要写服装、身份、场景。"
)


def api_base() -> str:
    return os.environ.get("DRAMACLAW_API_URL", DEFAULT_API_URL).rstrip("/")


def project_name(title: str) -> str:
    """DramaClaw accepts letters, digits and underscores only (`validate_project_name`)."""
    plain = unicodedata.normalize("NFKD", title.replace("đ", "d").replace("Đ", "D"))
    plain = "".join(ch for ch in plain if not unicodedata.combining(ch))
    slug = re.sub(r"[^A-Za-z0-9]+", "_", plain).strip("_")
    return f"{slug[:48]}_{time.strftime('%m%d%H%M')}"


def create_project(title: str) -> str:
    response = httpx.post(f"{api_base()}/api/v1/projects", json={"name": project_name(title)}, timeout=60)
    response.raise_for_status()
    data = response.json()
    body = data.get("data", data)
    project_id = str(body.get("id") or body.get("project_id") or body.get("name") or "")
    if not project_id:
        raise RunStopped(f"project create returned no id: {str(data)[:200]}")
    return project_id


def prepare_project(tools: DramaClawTools, story_path: Path, *, spine: str, settings: dict[str, Any]) -> None:
    text = chapter_text(story_path.read_text(encoding="utf-8"))
    filename = "story.txt"
    upload = httpx.post(
        f"{api_base()}/api/v1/projects/{tools.project_id}/ingest/upload",
        files={"file": (filename, text.encode("utf-8"), "text/plain")},
        timeout=120,
    )
    upload.raise_for_status()
    # The spine is project config read by ingest's format check; ingest/start accepts it only on a rebuild.
    spined = tools.request("PATCH", f"/projects/{tools.project_id}", body={"spine_template": spine})
    if spined.get("ok") is False:
        raise RunStopped(f"spine: {spined.get('error')}")
    started = tools.request(
        "POST", f"/projects/{tools.project_id}/ingest/start", body={"filename": filename, "rebuild": False}
    )
    if started.get("ok") is False:
        raise RunStopped(f"ingest start: {started.get('error')}")
    wait_task(tools, "ingest_fast", 0)
    patched = tools.request("PATCH", f"/projects/{tools.project_id}", body={"spine_template": spine, **settings})
    if patched.get("ok") is False:
        raise RunStopped(f"configure: {patched.get('error')}")


def _relay_token() -> str:
    """DramaClaw's own NewAPI relay token, read inside its container (never stored by us)."""
    code = (
        "from novelvideo.model_gateway_settings import get_model_gateway_settings as g;"
        "print(g()['custom_newapi_api_key'])"
    )
    out = subprocess.run(
        ["docker", "exec", "assembly-dramaclaw-api-1", "python", "-c", code],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return out.strip().splitlines()[-1]


TEXT_RETRIES = 3  # ASSEMBLY_PLAN §0: text calls retried 3 times, media once


def _chat_with_retries(token: str, payload: dict[str, Any]) -> httpx.Response:
    for attempt in range(TEXT_RETRIES + 1):
        response = httpx.post(
            f"{NEWAPI_URL}/v1/chat/completions",
            headers={"Authorization": f"Bearer {token}"},
            json=payload,
            timeout=180,
        )
        if response.status_code != 429 and response.status_code < 500:
            response.raise_for_status()
            return response
        if attempt < TEXT_RETRIES:
            time.sleep(30 * (attempt + 1))
    response.raise_for_status()
    return response


def fill_face_prompts(run: FilmRun, missing: list[dict[str, Any]]) -> None:
    if not missing:
        return
    token = _relay_token()
    for char in missing:
        facts = {k: char.get(k) for k in ("name", "gender", "age_group", "description", "role")}
        response = _chat_with_retries(
            token,
            {
                "model": "DC-identity-appearance-writer-LLM",
                "messages": [
                    {"role": "system", "content": FACE_PROMPT_RULE + " 只输出这一句描述。"},
                    {"role": "user", "content": json.dumps(facts, ensure_ascii=False)},
                ],
                "max_tokens": 200,
            },
        )
        face = str(response.json()["choices"][0]["message"]["content"]).strip()
        result = run.tools.call("dramaclaw_update_character_face_prompt", name=char["name"], face_prompt=face)
        if result.get("ok") is False:
            raise RunStopped(f"face_prompt {char['name']}: {result.get('error')}")


def _sample(text: str, preset: str) -> bytes:
    response = httpx.post(
        f"{VIENEU_URL}/v1/audio/speech",
        json={"input": text, "voice": preset, "response_format": "wav"},
        timeout=300,
    )
    response.raise_for_status()
    return response.content


def _upload(path: str, data: bytes, filename: str) -> None:
    response = httpx.post(f"{api_base()}/api/v1{path}", files={"file": (filename, data, "audio/wav")}, timeout=120)
    response.raise_for_status()
    body = response.json()
    if body.get("ok") is False:
        raise RunStopped(f"voice upload {path}: {body.get('error')}")


def cast_voices(run: FilmRun, *, story_region: str = "north") -> None:
    chars = run.characters()
    members = [CastMember(c["name"], str(c.get("gender") or "")) for c in chars]
    narrator_gender = "male"
    chosen = cast(members, load_voices(), story_region=story_region, narrator_gender=narrator_gender)
    project = run.state.project_id
    narrator_sample = _sample(NARRATOR_LINE, chosen["__narrator__"])
    registry.register(narrator_sample, chosen["__narrator__"])
    _upload(f"/projects/{project}/narrator-voice/upload", narrator_sample, "narrator.wav")
    for char in chars:
        preset = chosen[char["name"]]
        sample = _sample(SAMPLE_LINE.format(name=char["name"]), preset)
        registry.register(sample, preset)
        _upload(f"/projects/{project}/characters/{char['name']}/voice-samples/default/upload", sample, "voice.wav")
    run.state.voices_cast = chosen
    run.state.save(run.state_path)
